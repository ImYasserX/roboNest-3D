// Conventions
// - IDs are random UUID strings generated by the application.
// - Timestamps are integer milliseconds since epoch (Drizzle maps them to Date).
// - Money is an integer number of whole Iraqi dinars (IQD has no fractional
//   unit in practice). Never store money as REAL.
// - Bilingual content is stored as explicit *_en / *_ar columns.

const id = () =>
  text("id")
    .primaryKey()
    .$defaultFn(() => crypto.randomUUID());
const createdAt = () =>
  integer("created_at", { mode: "timestamp_ms" })
    .notNull()
    .$defaultFn(() => new Date());
const updatedAt = () =>
  integer("updated_at", { mode: "timestamp_ms" })
    .notNull()
    .$defaultFn(() => new Date())
    .$onUpdateFn(() => new Date());
const bool = (name: string) => integer(name, { mode: "boolean" });

